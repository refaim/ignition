#!/usr/bin/env python3
"""Generates C structs from tools/structs/*.def.

A .def file describes one struct of the original by offset:

    struct car 0x484c 0x5daffc       name, size, where the original keeps it
    0x000 double x                   offset, type, name, then a comment
    0x3dc s32 f3dc[8] 0x28           an array; a 4th field is its stride

Gaps become u8 padding; every field gets an offsetof assert, and the
struct a sizeof assert. Types: u8 s8 u16 s16 u32 s32 float double ptr
(a 32 bit pointer in the original: kept as u32 here) or a struct name.
An array with a stride other than its type's size becomes an array of
anonymous structs.

    python3 tools/gen_structs.py            writes src/structs/<name>.h
"""

import pathlib
import re
import sys

SIZES = {"u8": 1, "s8": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4,
         "float": 4, "double": 8, "ptr": 4}
CTYPE = {"ptr": "u32"}


def parse(path):
    fields, head = [], None
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split(None, 3)
        if parts[0] == "struct":
            head = (parts[1], int(parts[2], 16), parts[3] if len(parts) > 3 else "")
            continue
        off = int(parts[0], 16)
        typ, name = parts[1], parts[2]
        rest = parts[3] if len(parts) > 3 else ""
        m = re.match(r"(\w+)\[(\d+)\]$", name)
        count = int(m.group(2)) if m else 1
        base = m.group(1) if m else name
        stride = None
        comment = rest
        sm = re.match(r"(0x[0-9a-fA-F]+)\s*(.*)$", rest)
        if m and sm:
            stride, comment = int(sm.group(1), 16), sm.group(2)
        fields.append((off, typ, base, count, stride, comment))
    return head, sorted(fields)


def emit(head, fields):
    name, size, where = head
    out = [f"/* Generated by tools/gen_structs.py from tools/structs/{name}.def. */", "",
           f"#ifndef IGN_STRUCT_{name.upper()}_H", f"#define IGN_STRUCT_{name.upper()}_H", "",
           "#include <stddef.h>", "", '#include "types.h"', ""]
    out.append(f"/* {size:#x} bytes{', at ' + where if where else ''} in the original. */")
    out.append("#pragma pack(push, 1)")
    out.append(f"struct {name} {{")
    at = 0
    for off, typ, base, count, stride, comment in fields:
        if off < at:
            sys.exit(f"{name}: field {base} at {off:#x} overlaps")
        if off > at:
            out.append(f"    u8 pad_{at:03x}[{off - at:#x}];")
        el = SIZES.get(typ, 0)
        ctype = CTYPE.get(typ, typ)
        if typ not in SIZES:
            sys.exit(f"{name}: unknown type {typ}")
        c = f"  /* {comment} */" if comment else ""
        if count > 1 and stride and stride != el:
            out.append(f"    struct {{ {ctype} v; u8 pad[{stride - el:#x}]; }} {base}[{count}];"
                       f"  /* +{off:#x}{', ' + comment if comment else ''} */")
            at = off + stride * count
        else:
            dims = f"[{count}]" if count > 1 else ""
            out.append(f"    {ctype} {base}{dims};  /* +{off:#x}{', ' + comment if comment else ''} */")
            at = off + el * count
    if at > size:
        sys.exit(f"{name}: fields end at {at:#x}, past the size")
    if at < size:
        out.append(f"    u8 pad_{at:03x}[{size - at:#x}];")
    out.append("};")
    out.append("#pragma pack(pop)")
    out.append("")
    for off, typ, base, count, stride, comment in fields:
        out.append(f"_Static_assert(offsetof(struct {name}, {base}) == {off:#x}, \"{name}.{base}\");")
    out.append(f"_Static_assert(sizeof(struct {name}) == {size:#x}, \"{name}\");")
    out.append("")
    out.append(f"#endif /* IGN_STRUCT_{name.upper()}_H */")
    return "\n".join(out) + "\n"


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    dst = root / "src" / "structs"
    dst.mkdir(exist_ok=True)
    for path in sorted((root / "tools" / "structs").glob("*.def")):
        head, fields = parse(path)
        (dst / f"{head[0]}.h").write_text(emit(head, fields))
        print(f"src/structs/{head[0]}.h: {len(fields)} fields")


if __name__ == "__main__":
    main()
