"""Write docs/PROGRESS.md: which routines of IGN_WIN.EXE have a C version.

A routine counts as ported when a function in src/ carries its address
in a comment ("/* 0x45b5c0 */" above the definition), and as stubbed
when src/stubs.h declares it. Runtime library code that IDA recognised
from signatures (tools/library_funcs.txt) is left out. Needs .ida-mcp/index.json from
tools/ida_index.py.

    python3 -I tools/progress.py
"""
import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "docs", "PROGRESS.md")


def scan():
    ported, stubbed = {}, {}
    above = re.compile(r"^/\*\s*(?:\w+\s+)?(0x(?:4|64)[0-9a-f]{4,5})\b")
    defn = re.compile(r"^(?:static\s+)?[A-Za-z_][\w\s\*]*?\b([A-Za-z_]\w*)\(")
    decl = re.compile(r"\b([A-Za-z_]\w*)\([^;]*\);\s*/\*\s*(0x4[0-9a-f]{5})")
    for path in glob.glob(os.path.join(SRC, "**", "*.[ch]"), recursive=True):
        rel = os.path.relpath(path, ROOT)
        lines = open(path, encoding="latin1").read().split("\n")
        for i, line in enumerate(lines):
            if path.endswith("stubs.h"):
                m = decl.search(line)
                if m:
                    stubbed[int(m.group(2), 16)] = (m.group(1), rel)
                continue
            m = above.match(line)
            if not m:
                continue
            for j in range(i + 1, min(i + 16, len(lines))):
                d = defn.match(lines[j])
                if d and not lines[j].startswith((" ", "\t", "/", "*", "#")):
                    ported.setdefault(int(m.group(1), 16), (d.group(1), rel))
                    break
    return ported, stubbed


def main():
    index = json.load(open(os.path.join(ROOT, ".ida-mcp", "index.json")))
    ported, stubbed = scan()
    library = set()
    for line in open(os.path.join(ROOT, "tools", "library_funcs.txt")):
        if line.strip() and not line.startswith("#"):
            library.add(int(line.split()[0], 16))
    game = {int(a, 16): f for a, f in index.items() if int(a, 16) not in library}
    total = sum(f["size"] for f in game.values())
    done = sum(game[a]["size"] for a in ported if a in game)
    rows = []
    for a in sorted(game):
        f = game[a]
        if a in ported:
            status, name, where = "ported", ported[a][0], ported[a][1]
        elif a in stubbed:
            status, name, where = "stub", stubbed[a][0], stubbed[a][1]
        else:
            continue
        rows.append("| `0x%x` | %d | %s | `%s` | `%s` |" % (a, f["size"], status, name, where))
    with open(OUT, "w") as fp:
        fp.write("# Port progress\n\n")
        fp.write("Generated by `tools/progress.py`. Do not edit by hand.\n\n")
        fp.write("Game routines in `IGN_WIN.EXE` (runtime library code excluded): "
                 "%d, %d bytes of code.\n\n" % (len(game), total))
        fp.write("- Ported: %d routines, %d bytes (%.1f%%)\n" % (
            sum(1 for a in ported if a in game), done, 100.0 * done / total))
        fp.write("- Stubbed: %d routines\n\n" % sum(1 for a in stubbed if a in game and a not in ported))
        fp.write("| Address | Size | Status | C name | File |\n|---|---|---|---|---|\n")
        fp.write("\n".join(rows) + "\n")
    print(open(OUT).read().split("\n| Address")[0])


if __name__ == "__main__":
    main()
